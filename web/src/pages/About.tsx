/** Info card with an icon box: title, then body. */
function Note({ icon, title, children, tone = "" }: { icon: keyof typeof PATHS; title: string; children: ReactNode; tone?: string }) {
  return (
    <div className={`about-note ${tone}`}>
      <span className="about-icon"><Icon size={26}>{PATHS[icon]}</Icon></span>
      <div><h3>{title}</h3>{children}</div>
    </div>
  );
}

